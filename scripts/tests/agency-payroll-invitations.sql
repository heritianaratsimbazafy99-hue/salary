\set ON_ERROR_STOP on
begin;
set local timezone='UTC';
do $$
declare a uuid; actor uuid; hr uuid; emp uuid; i uuid; fingerprint text; jobs jsonb; job uuid; rev integer; life integer; auth_id uuid:=gen_random_uuid();
begin
 insert into public.agencies(name,code) values('Lifecycle payroll','LCP-'||gen_random_uuid()) returning id into a;
 insert into auth.users(id,email,email_confirmed_at) values(auth_id,gen_random_uuid()||'@lifecycle.test',now());
 insert into public.profiles(auth_user_id,email,full_name,role) values(auth_id,gen_random_uuid()||'@lifecycle.test','Payroll','agency_manager') returning id into actor;
 insert into public.profiles(email,full_name,role) values(gen_random_uuid()||'@lifecycle.test','RH','hr_central') returning id into hr;
 insert into public.agency_memberships(profile_id,agency_id) values(actor,a);
 emp:=public.agency_create_employee(actor,a,'LCP-001','lifecycle-payroll@example.test','Corrected Name');
 jobs:=public.queue_agency_invitations(actor,a,array[emp],gen_random_uuid());
 if jsonb_array_length(jobs)<>1 then raise exception 'invitation not queued'; end if;
 job:=(jobs->>0)::uuid;
 if public.claim_agency_invitation(job,repeat('a',64))->>'email'<>'lifecycle-payroll@example.test' then raise exception 'claim missing'; end if;
 if public.claim_agency_invitation(job,repeat('a',64)) is not null then raise exception 'lease duplicate'; end if;
 select revision into rev from public.employees where id=emp;
 select revision into life from public.employee_employment_lifecycle where employee_id=emp;
 perform public.agency_depart_employee(actor,emp,rev,life,current_date,'Départ confirmé');
 update public.agency_invitation_jobs set lease_until=now()-interval '1 minute' where id=job;
 if public.claim_agency_invitation(job,repeat('a',64)) is not null then raise exception 'departed claim allowed'; end if;
 if not exists(select 1 from public.agency_invitation_jobs where id=job and status='SKIPPED') then raise exception 'departure did not cancel job'; end if;
 update public.employees set is_active=false where id=emp;
 insert into public.payroll_imports(agency_id,period_start,period_end,uploaded_by,source_filename,status) values(a,'2026-10-01','2026-10-31',actor,'lifecycle.xlsx','READY_FOR_PREVIEW') returning id into i;
 insert into public.payroll_import_rows(import_id,agency_id,employee_id,employee_email,employee_name,normalized_data) values(i,a,'LCP-001','lifecycle-payroll@example.test','Historical Name','{"grossAmount":100,"deductionsTotal":10,"netAmount":90,"employeeName":"Historical Name"}');
 perform set_config('request.jwt.claim.sub',auth_id::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',auth_id,'role','authenticated')::text,true);
 execute 'set local role authenticated';
 if public.review_payroll_import(i)->>'fingerprint' is null then raise exception 'authenticated manager review inaccessible'; end if;
 begin perform 1 from public.employee_employment_lifecycle limit 1; raise exception 'private lifecycle table leaked'; exception when insufficient_privilege then null; end;
 perform set_config('request.jwt.claim.sub',gen_random_uuid()::text,true);
 perform set_config('request.jwt.claims',jsonb_build_object('sub',gen_random_uuid(),'role','authenticated')::text,true);
 begin perform public.review_payroll_import(i); raise exception 'unassigned actor review allowed'; exception when insufficient_privilege then null; end;
 execute 'reset role';
 perform set_config('request.jwt.claims','{}',true);
 perform set_config('request.jwt.claim.sub','',true);
 fingerprint:=public.review_payroll_import(i)->>'fingerprint';
 if not (public.review_payroll_import(i)->'recipients'->0->>'departed')::boolean then raise exception 'missing departure warning'; end if;
 begin perform public.publish_payroll_import_reviewed(i,actor,a,fingerprint); raise exception 'departed publication lacked approval'; exception when sqlstate 'PT409' then null; end;
 perform public.approve_departed_payroll(hr,i,fingerprint);
 update public.employees set full_name='Second Corrected Name' where id=emp;
 begin perform public.publish_payroll_import_reviewed(i,actor,a,fingerprint); raise exception 'identity revision did not invalidate review'; exception when sqlstate 'PT409' then null; end;
 fingerprint:=public.review_payroll_import(i)->>'fingerprint';
 begin perform public.publish_payroll_import_reviewed(i,actor,a,fingerprint); raise exception 'old approval accepted'; exception when sqlstate 'PT409' then null; end;
 perform public.approve_departed_payroll(hr,i,fingerprint);
 perform public.publish_payroll_import_reviewed(i,actor,a,fingerprint);
 if not exists(select 1 from public.employees where id=emp and full_name='Second Corrected Name' and not is_active) then raise exception 'publication rewrote dossier or access'; end if;
 if not exists(select 1 from public.employee_employment_lifecycle where employee_id=emp and state='DEPARTED') then raise exception 'publication reactivated employment'; end if;
 if not exists(select 1 from public.payslip_versions where import_id=i and snapshot_data->>'employeeName'='Historical Name') then raise exception 'snapshot source name changed'; end if;
end $$;
rollback;
